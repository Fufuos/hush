use sqlx::SqlitePool;
use sqlx::sqlite::{SqliteConnectOptions, SqlitePoolOptions};
use std::str::FromStr;

/// Initializes the SQLite database pool and ensures the file and schema exist.
pub async fn init_db(database_url: &str) -> SqlitePool {
    // 1. Parse the URL and tell SQLite to create the file if it doesn't exist
    let connection_options = SqliteConnectOptions::from_str(database_url)
        .expect("Invalid database URL")
        .create_if_missing(true);

    // 2. Connect using those options and establish a connection pool
    let pool = SqlitePoolOptions::new()
        .max_connections(5)
        .connect_with(connection_options)
        .await
        .expect("Failed to connect to SQLite");

    // 3. Automatically create the required table if it doesn't exist.
    // We store ciphertext and nonce as BLOBs to perfectly match the raw bytes
    // generated by our AES-GCM logic in hush-core.
    sqlx::query(
        r#"
        CREATE TABLE IF NOT EXISTS secrets (
            id TEXT PRIMARY KEY NOT NULL,
            name TEXT UNIQUE NOT NULL,
            ciphertext BLOB NOT NULL,
            nonce BLOB NOT NULL
        );
        "#,
    )
    .execute(&pool)
    .await
    .expect("❌ Failed to initialize database schema");

    println!("✅ Database connection established and schema verified.");

    pool
}
